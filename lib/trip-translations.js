// cfg: days, diff, region, stay, size (people helper result), depart
function T(cfg, ka, ru, zh) {
  const out = {};
  for (const [l, f] of [['ka', ka], ['ru', ru], ['zh', zh]]) {
    out[l] = {
      ...(cfg.days ? dur(cfg.days)[l] : {}),
      ...(cfg.diff ? { difficulty: DIFF[cfg.diff][l] } : {}),
      ...(cfg.region ? { region: REGION[cfg.region][l] } : {}),
      ...(cfg.stay ? { stay: STAY[cfg.stay][l] } : {}),
      ...(cfg.size ? { group_size: cfg.size[l] } : {}),
      ...(cfg.depart ? { departure_point: cfg.depart[l] } : {}),
      ...f,
    };
  }
  return out;
}

