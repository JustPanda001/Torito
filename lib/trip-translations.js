// The trip page and cards read included / excluded as {title, note}; the
// authoring shape above is [label, detail] to match tours-data.js.
const asNote = ([title, note]) => ({ title, note });
for (const langs of Object.values(TRIP_TEXT)) {
  for (const tr of Object.values(langs)) {
    if (tr.included) tr.included = tr.included.map(asNote);
    if (tr.excluded) tr.excluded = tr.excluded.map(asNote);
  }
}

/** The trip with its text swapped into `lang` wherever a translation exists. */
export function localizeTour(tour, lang) {
  const tr = tour && lang !== 'en' ? TRIP_TEXT[tour.slug]?.[lang] : null;
  if (!tr) return tour;
  const out = { ...tour };
  for (const [field, value] of Object.entries(tr)) {
    if (value != null) out[field] = value;
  }
  // the trip page reads the practical details from a nested `info` object
  // (meeting point, transport, group size…), so translate those copies too
  if (tour.info) {
    out.info = { ...tour.info };
    for (const field of Object.keys(tour.info)) {
      if (tr[field] != null) out.info[field] = tr[field];
    }
  }
  return out;
}
